import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const phonesDirectory = resolve(scriptDirectory, '../../data/phones');
const outputPath = resolve(scriptDirectory, '../src/lib/server/catalogue.generated.ts');

function fail(filename, message) {
  throw new Error(`Invalid phone document ${filename}: ${message}`);
}

function record(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function nonEmptyString(value) {
  return typeof value === 'string' && value.length > 0;
}

function validatePhone(phone, filename) {
  if (!record(phone)) fail(filename, 'document must be an object');
  for (const field of ['id', 'brand', 'name', 'narrative']) {
    if (!nonEmptyString(phone[field])) fail(filename, `${field} must be a non-empty string`);
  }
  if (!record(phone.specs)) fail(filename, 'specs must be an object');
  if (!record(phone.signals)) fail(filename, 'signals must be an object');
  if (!Array.isArray(phone.signals.use_cases) || !phone.signals.use_cases.every(nonEmptyString)) {
    fail(filename, 'signals.use_cases must be an array of strings');
  }
  if (!Array.isArray(phone.signals.personas) || !phone.signals.personas.every(nonEmptyString)) {
    fail(filename, 'signals.personas must be an array of strings');
  }
  if (typeof phone.signals.price_segment !== 'string') {
    fail(filename, 'signals.price_segment must be a string');
  }
  if (!Array.isArray(phone.colors) || phone.colors.length === 0) {
    fail(filename, 'colors must contain at least one option');
  }
  phone.colors.forEach((color, index) => {
    if (!record(color)) fail(filename, `colors[${index}] must be an object`);
    for (const field of ['name', 'family', 'image']) {
      if (!nonEmptyString(color[field])) fail(filename, `colors[${index}].${field} must be a non-empty string`);
    }
    if (color.hex !== undefined && typeof color.hex !== 'string') {
      fail(filename, `colors[${index}].hex must be a string`);
    }
  });
  if (!Array.isArray(phone.storage_options) || phone.storage_options.length === 0) {
    fail(filename, 'storage_options must contain at least one option');
  }
  phone.storage_options.forEach((option, index) => {
    if (!record(option)) fail(filename, `storage_options[${index}] must be an object`);
    if (!Number.isInteger(option.gb)) fail(filename, `storage_options[${index}].gb must be an integer`);
    if (!nonEmptyString(option.label)) fail(filename, `storage_options[${index}].label must be a non-empty string`);
    if (!Number.isInteger(option.price)) fail(filename, `storage_options[${index}].price must be an integer`);
    if (option.ram_gb !== undefined && !Number.isInteger(option.ram_gb)) {
      fail(filename, `storage_options[${index}].ram_gb must be an integer`);
    }
  });
}

const filenames = (await readdir(phonesDirectory)).filter((name) => name.endsWith('.json')).sort();
if (filenames.length === 0) throw new Error(`No phone documents found in ${phonesDirectory}`);

const phones = [];
const ids = new Set();
for (const filename of filenames) {
  let phone;
  try {
    phone = JSON.parse(await readFile(resolve(phonesDirectory, filename), 'utf8'));
  } catch (error) {
    fail(filename, error instanceof Error ? error.message : String(error));
  }
  validatePhone(phone, filename);
  if (ids.has(phone.id)) fail(filename, `duplicate id: ${phone.id}`);
  ids.add(phone.id);
  phones.push(phone);
}

const output = `// Generated by scripts/generate-catalogue.mjs from data/phones. Do not edit.\n\nimport type { CataloguePhone } from '$lib/schema';\n\nexport const CATALOGUE: readonly CataloguePhone[] = ${JSON.stringify(phones, null, 2)};\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = await readFile(outputPath, 'utf8');
  } catch {}
  if (current !== output) {
    console.error('Catalogue artifact is stale. Run npm run generate:catalogue.');
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, output);
  console.log(`Generated ${phones.length} phones in ${outputPath}`);
}
